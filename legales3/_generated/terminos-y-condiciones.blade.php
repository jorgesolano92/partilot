<p>La liquidación definitiva, una vez confirmada mediante el procedimiento de seguridad establecido, no podrá ser modificada, cancelada ni revertida bajo ninguna circunstancia. PARTILOT no asumirá responsabilidad por errores derivados de una liquidación incorrecta o precipitada, conforme al deslinde establecido en el artículo 4.1 bis.</p>

<p><strong>Regla especial:</strong> sorteos con Premio Especial al décimo (décimos de 15 €)</p>

<p>En estos sorteos, el premio total se obtiene sumando la totalidad de los premios de todos los décimos del listado validado (premio base del Primer Premio por décimo más el Premio Especial). El importe resultante se divide en partes iguales entre todas las participaciones vendidas de ese número, con independencia del importe jugado en cada una.</p>

<p><strong>Fórmula:</strong> Premio total = (Premio base × nº de décimos adjudicados) + Premio Especial. Premio por participación = Premio total ÷ nº de participaciones vendidas. Ejemplo: 5 décimos, premio base 400.000 €/décimo, Premio Especial 200.000 €. Premio total = 2.200.000 €. Con 1.000 participaciones vendidas: 2.200 € por participación.</p>


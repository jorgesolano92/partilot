<p>PARTILOT gestiona exclusivamente premios menores, es decir, aquellos cuyo importe individual no supera el umbral a partir del cual la normativa fiscal española establece la obligación de practicar retención de IRPF. Los premios que superen dicho umbral deben ser cobrados directamente por la Entidad, fuera del ámbito de este servicio.</p>


<p>Cuando una participación resulta premiada y la Entidad ha habilitado el servicio de gestión de pagos, el Usuario Final deberá elegir el destino del premio en el mismo acto de cobro, entre transferencia bancaria, donación a la Entidad, o generación de código de recarga. Las tres modalidades son excluyentes entre sí para cada operación y, una vez confirmadas, completamente irreversibles. No existe saldo, bolsa ni acumulación de importes premiados en la Plataforma a nombre del Usuario Final.</p>

<p>Modalidad A — Transferencia bancaria</p>

<p>El usuario solicita la transferencia del importe premiado a su IBAN. Una vez confirmada, la operación es irreversible. Si el banco rechaza la transferencia por datos incorrectos, la participación retorna al estado pendiente de cobro.</p>

<p>Modalidad B — Donación a la Entidad emisora</p>

<p>El usuario puede donar todo o parte del premio. Antes de confirmar, debe aceptar expresamente que: el importe se transfiere íntegramente a la Entidad; la donación es irreversible; la facilitación de datos fiscales para certificado es voluntaria; y la emisión del certificado es responsabilidad exclusiva de la Entidad.</p>

<p>Modalidad C — Generación de código de recarga</p>

<p>El usuario puede convertir el premio en un código canjeable en la web del Punto de Venta Autorizado. Debe aceptar expresamente que: supone renuncia irrevocable al cobro en metálico; equivale al 100% del importe sin comisión; tiene fecha de caducidad visible antes de la confirmación; es de uso único y personal; y solo es canjeable en la web del Punto de Venta Autorizado vinculado a la Entidad emisora.</p>


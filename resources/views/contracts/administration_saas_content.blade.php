    <p><strong>EXPONEN</strong></p>
    <p>I. Que PARTILOT es titular y opera una plataforma tecnológica de gestión integral denominada PARTILOT (en adelante, «la Plataforma»), orientada a la digitalización y automatización de los procesos de gestión de participaciones de lotería para Administraciones de Lotería, Entidades, Vendedores y Usuarios Finales.</p>
    <p>II. Que la Administración es titular de un punto de venta autorizado por Loterías y Apuestas del Estado (SELAE) y desea incorporar la Plataforma como herramienta de gestión de sus operaciones de participaciones de lotería.</p>
    <p>III. Que ambas partes desean regular mediante el presente contrato los derechos, obligaciones y responsabilidades derivados de la prestación del servicio.</p>
    <p>En su virtud, las partes suscriben el presente contrato con arreglo a las siguientes</p>

    <p><strong>CLÁUSULAS</strong></p>

    <p><strong>CLÁUSULA 1 — OBJETO</strong><br>
    El presente contrato tiene por objeto la prestación por PARTILOT a la Administración del servicio de acceso y uso de la Plataforma (en adelante, «el Servicio»), en la modalidad de software como servicio, que comprende: el acceso al panel de gestión web y a la aplicación móvil de PARTILOT; la creación y gestión de reservas de décimos y sets vinculados a las Entidades; herramientas de escrutinio, liquidación y cierre del ciclo comercial; y soporte técnico y documentación disponibles en la Plataforma. PARTILOT actúa en todo momento como proveedor tecnológico y no interviene en las relaciones comerciales entre la Administración, las Entidades, los Vendedores y los Usuarios Finales.</p>

    <p><strong>CLÁUSULA 2 — DURACIÓN Y ENTRADA EN VIGOR</strong><br>
    2.1 El contrato entra en vigor en la fecha de su firma electrónica por ambas partes. La firma queda registrada con identificación del firmante, marca temporal y dirección IP, conforme al Reglamento (UE) nº 910/2014 y la Ley 6/2020.<br>
    2.2 Duración inicial de un (1) año, renovable automáticamente por períodos anuales salvo denuncia con preaviso mínimo de treinta (30) días naturales.<br>
    2.3 Resolución anticipada con preaviso mínimo de noventa (90) días naturales, sin eximir del pago de cuotas devengadas.</p>

    <p><strong>CLÁUSULA 3 — CONDICIONES ECONÓMICAS Y FORMA DE PAGO</strong><br>
    3.1 La incorporación es gratuita.<br>
    3.2 El uso del Servicio se retribuye mediante cuota de gestión devengada al generar cada set, conforme a tarifas publicadas en la Plataforma.<br>
    3.3 Cada set puede configurarse para que la cuota corra a cargo de la Administración o de la Entidad.<br>
    3.4 Cobro mediante TPV integrado o domiciliación SEPA Core.<br>
    3.5 Saldo de servicio por participaciones no vendidas declaradas en cierre: no reembolsable en efectivo, canjeable en Plataforma, caduca a los quince (15) meses.<br>
    3.6 Importes sin IVA; factura por cada cuota devengada.<br>
    3.7 Impago faculta a PARTILOT para suspender el acceso, previa notificación de diez (10) días hábiles.</p>

    <p><strong>CLÁUSULA 4 — OBLIGACIONES DE PARTILOT</strong><br>
    Prestar el Servicio con diligencia debida; notificar mantenimientos programados; incorporar resultados oficiales SELAE; mantener medidas de seguridad del Marco Legal Integral; notificar brechas en 72 horas; proporcionar soporte; conservar datos conforme al Acuerdo de Tratamiento de Datos.</p>

    <p><strong>CLÁUSULA 5 — OBLIGACIONES DE LA ADMINISTRACIÓN</strong><br>
    Información veraz y actualizada; custodia de credenciales; uso conforme a normativa; validación de escrutinios; gestión diligente de Entidades; pago puntual de cuotas; no cesión del acceso; cumplimiento normativa SELAE; custodia de archivos digitales de participaciones físicas. Las cláusulas 5.1 a 5.5 sobre contenidos y diseños creados en la Plataforma se aceptan íntegramente, incluyendo responsabilidad exclusiva sobre legalidad de diseños, textos e imágenes.</p>

    <p><strong>CLÁUSULA 6 — LIMITACIÓN DE RESPONSABILIDAD</strong><br>
    Exclusiones y límite máximo de responsabilidad conforme al texto íntegro del contrato SaaS PARTILOT v{{ $contractVersion }}.</p>

    <p><strong>CLÁUSULA 7 — PROPIEDAD INTELECTUAL Y CONFIDENCIALIDAD</strong><br>
    Titularidad exclusiva de PARTILOT sobre la Plataforma; obligación de confidencialidad durante la vigencia y cinco (5) años posteriores.</p>

    <p><strong>CLÁUSULA 8 — SERVICIO OPCIONAL DE GESTIÓN TÉCNICA DE PAGOS DE PREMIOS</strong><br>
    Requiere Acuerdo Específico de Mandato de Pago por sorteo entre Entidad y PARTILOT, independiente del presente contrato.</p>

    <p><strong>CLÁUSULA 9 — MODIFICACIÓN DEL SERVICIO Y DE LAS CONDICIONES</strong><br>
    Modificaciones con preaviso mínimo de treinta (30) días; discontinuación con noventa (90) días.</p>

    <p><strong>CLÁUSULA 10 — PROTECCIÓN DE DATOS</strong><br>
    Régimen RGPD, LOPDGDD y Acuerdo de Tratamiento de Datos del Marco Legal Integral.</p>

    <p><strong>CLÁUSULA 11 — CAUSAS DE RESOLUCIÓN</strong><br>
    Incumplimiento grave, impago de dos cuotas consecutivas, pérdida de autorización SELAE, concurso, uso ilícito de la Plataforma, entre otras previstas en el texto íntegro.</p>

